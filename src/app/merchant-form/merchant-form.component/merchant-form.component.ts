import { Component, inject, signal } from '@angular/core';
import { FormBuilder, FormControl, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { MerchantFormStep1 } from '../../merchant-form-steps/merchant-form-step-1/merchant-form-step-1';
import { MerchantFormStep2 } from '../../merchant-form-steps/merchant-form-step-2/merchant-form-step-2';
import { MerchantFormStep3 } from '../../merchant-form-steps/merchant-form-step-3/merchant-form-step-3';
import { MatStepperModule } from '@angular/material/stepper';
import { MatFormFieldModule } from '@angular/material/form-field';
import { MatInputModule } from '@angular/material/input';
import { MatButtonModule, MatAnchor } from '@angular/material/button';
import {
  debounceTime,
  distinctUntilChanged,
  switchMap,
  catchError,
  EMPTY,
  tap
} from 'rxjs';
import { MerchantFormStep4 } from '../../merchant-form-steps/merchant-form-step-4/merchant-form-step-4';
import { ActivatedRoute } from '@angular/router';
import { DataService } from '../../services/data/data-service';

@Component({
  selector: 'app-merchant-form.component',
  imports: [
    MatStepperModule,
    MerchantFormStep1,
    MerchantFormStep2,
    MerchantFormStep3,
    MerchantFormStep4,
    ReactiveFormsModule,
    MatInputModule,
    MatFormFieldModule,
    MatButtonModule,
    MatAnchor
  ],
  templateUrl: './merchant-form.component.html',
  styleUrl: './merchant-form.component.scss',
})
export class MerchantFormComponent {

  isEditMode = signal(false);
  merchantId = signal<number | null>(null);

  private _formBuilder = inject(FormBuilder);
  private route = inject(ActivatedRoute);
  private dataService = inject(DataService);

  registrationForm: FormGroup = new FormGroup({
    companyDetails: this._formBuilder.group({
      companyName: new FormControl('', Validators.required),
      categoryCode: new FormControl(''),
      businessWebsite: new FormControl(''),
      panNumber: new FormControl('', Validators.required),
    }),
    contactDetails: this._formBuilder.group({
      email: new FormControl('', [Validators.required, Validators.email]),
      phone: new FormControl(''),
    }),
    bankDetails: this._formBuilder.group({
      bankName: new FormControl(''),
      accountHolderName: new FormControl(''),
      accountNumber: new FormControl(''),
      cardNumber: new FormControl(''),
    })
  });


  ngOnInit() {
    const id = this.route.snapshot.paramMap.get('id');

    if (id) {
      this.isEditMode.set(true);
      this.merchantId.set(Number(id));
      this.populateForm(Number(id));
    } else {
      //set new id for new form which is used to save draft
      // usually this id will be generated by backend but for now we are generating it here
      const newId = this.dataService.merchants().length + 1;
      this.merchantId.set(newId);
    }
    this.initializeAutosave();
  }

  populateForm(id: number) {
    // Fetch the merchant data based on the ID and populate the form
    // For demonstration, let's assume we have a method to get the merchant data
    const merchantData = this.dataService.getMerchantById(id);
    if (merchantData) {
      this.registrationForm.patchValue({
        companyDetails: merchantData.companyDetails,
        contactDetails: merchantData.contactDetails,
        bankDetails: merchantData.bankDetails,
      });
    }
  }
  saveStatus = signal<string>('');
  initializeAutosave() {

    this.registrationForm.valueChanges.pipe(

      // Wait until the user stops typing
      debounceTime(800),

      // Avoid saving unchanged data
      distinctUntilChanged(
        (previous, current) =>
          JSON.stringify(previous) === JSON.stringify(current)
      ),

      tap(() => {
        this.saveStatus.set('saving');
      }),

      // Call autosave API
      switchMap(formData =>
        this.dataService.saveDraft(formData, Number(this.merchantId())).pipe(
          tap(() => this.saveStatus.set('saved')),
          catchError(error => {
            console.error('Autosave failed:', error);
            this.saveStatus.set('error');
            return EMPTY;
          })
        )
      ),

      // takeUntilDestroyed(this.destroyRef)

    ).subscribe();
  }

  saveDraft(): void {
    this.saveStatus.set('saving');

    this.dataService.saveDraft(
      this.registrationForm.getRawValue(),
      Number(this.merchantId())
    )
      .subscribe({
        next: () => this.saveStatus.set('saved'),
        error: () => this.saveStatus.set('error')
      });
  }

  formSubmitted: boolean = false;
  submitForm() {
    console.log('submitted');
    console.log(this.registrationForm.value);
    this.formSubmitted = true;
    alert('Your form has been submitted!');
  }
}
